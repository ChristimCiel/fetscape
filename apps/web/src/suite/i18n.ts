export type SuiteCopyKey = keyof (typeof suiteCopy)['en'];

export function tSuite(key: SuiteCopyKey, lang: Language): string {
  return suiteCopy[lang][key] ?? suiteCopy.en[key] ?? key;
}

export function allSuiteStrings(): { lang: Language; key: string; value: string }[] {
  const out: { lang: Language; key: string; value: string }[] = [];
  for (const lang of ['en', 'zh-TW'] as Language[]) {
    for (const [key, value] of Object.entries(suiteCopy[lang])) {
      out.push({ lang, key, value });
    }
  }
  return out;
}
